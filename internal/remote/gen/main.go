//go:build ignore

// Generates stores_gen.go: one routing wrapper per persistence.Stores field.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"log"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const persistencePath = "github.com/openvibely/openvibely/internal/persistence"
const sqlitePath = persistencePath + "/sqlite"

func main() {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName}, persistencePath, sqlitePath)
	if err != nil || len(pkgs) != 2 {
		log.Fatalf("load: %v %v", err, pkgs)
	}
	var scope *types.Scope
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			log.Fatalf("load %s: %v", p.PkgPath, p.Errors)
		}
		if p.PkgPath == persistencePath {
			scope = p.Types.Scope()
		} else {
			implNames = sqliteParamNames(p.Types)
		}
	}
	stores := scope.Lookup("Stores").Type().Underlying().(*types.Struct)
	imports := map[string]string{"context": "context", persistencePath: "persistence"}
	qual := func(p *types.Package) string {
		if p.Path() == "github.com/openvibely/openvibely/internal/remote" {
			return ""
		}
		name := p.Name()
		imports[p.Path()] = name
		return name
	}
	var body bytes.Buffer
	var wrapFields bytes.Buffer
	var meta bytes.Buffer
	for i := 0; i < stores.NumFields(); i++ {
		field := stores.Field(i)
		named := field.Type().(*types.Named)
		iface := named.Underlying().(*types.Interface)
		typeName := named.Obj().Name()
		fmt.Fprintf(&wrapFields, "\ts.%s = &%s{local: s.%s, r: r}\n", field.Name(), typeName, field.Name())
		fmt.Fprintf(&body, "type %s struct {\n\tlocal persistence.%s\n\tr *Router\n}\n\n", typeName, typeName)
		fmt.Fprintf(&body, "func (s *%s) Local() persistence.%s { return s.local }\n\n", typeName, typeName)
		methods := make([]*types.Func, 0, iface.NumMethods())
		for j := 0; j < iface.NumMethods(); j++ {
			methods = append(methods, iface.Method(j))
		}
		sort.Slice(methods, func(a, b int) bool { return methods[a].Name() < methods[b].Name() })
		fmt.Fprintf(&meta, "\t%q: {\n", field.Name())
		for _, m := range methods {
			sig := m.Type().(*types.Signature)
			writeMethod(&body, field.Name(), typeName, "s.local", m.Name(), sig, qual)
			fmt.Fprintf(&meta, "\t\t%q: {%s},\n", m.Name(), paramNames(named, m.Name(), sig))
		}
		fmt.Fprintf(&meta, "\t},\n")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by gen/main.go; DO NOT EDIT.\n\npackage remote\n\nimport (\n")
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&out, "\t%q\n", p)
	}
	out.WriteString(")\n\n")
	out.WriteString("// Wrap routes every store in s through r.\nfunc Wrap(s persistence.Stores, r *Router) persistence.Stores {\n")
	out.Write(wrapFields.Bytes())
	out.WriteString("\treturn s\n}\n\n")
	out.WriteString("// paramNames lists each method's parameter names after ctx.\nvar paramNames = map[string]map[string][]string{\n")
	out.Write(meta.Bytes())
	out.WriteString("}\n\n")
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		os.WriteFile("stores_gen.go", out.Bytes(), 0o644)
		log.Fatal(err)
	}
	if err := os.WriteFile("stores_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// implNames maps "Type.Method" in the sqlite package to its parameter names,
// used when the interface leaves them unnamed.
var implNames map[string][]string

func sqliteParamNames(pkg *types.Package) map[string][]string {
	out := map[string][]string{}
	scope := pkg.Scope()
	for _, name := range scope.Names() {
		tn, ok := scope.Lookup(name).(*types.TypeName)
		if !ok {
			continue
		}
		mset := types.NewMethodSet(types.NewPointer(tn.Type()))
		for i := 0; i < mset.Len(); i++ {
			fn, ok := mset.At(i).Obj().(*types.Func)
			if !ok {
				continue
			}
			sig := fn.Type().(*types.Signature)
			var names []string
			for j := 0; j < sig.Params().Len(); j++ {
				names = append(names, sig.Params().At(j).Name())
			}
			out[name+"."+fn.Name()] = names
		}
	}
	return out
}

// implParamNames finds the sqlite type implementing iface and returns its names.
func implParamNames(iface *types.Named, method string, sig *types.Signature) []string {
	var found []string
	for key, names := range implNames {
		if !strings.HasSuffix(key, "."+method) || len(names) != sig.Params().Len() {
			continue
		}
		named := false
		for _, n := range names {
			if n != "" && n != "_" {
				named = true
			}
		}
		if !named {
			continue
		}
		typ := key[:len(key)-len(method)-1]
		if typ == strings.TrimSuffix(iface.Obj().Name(), "Store")+"Repo" {
			return names
		}
		if found == nil {
			found = names
		}
	}
	return found
}

func paramNames(iface *types.Named, method string, sig *types.Signature) string {
	var impl []string
	var names []string
	for i := 0; i < sig.Params().Len(); i++ {
		p := sig.Params().At(i)
		if i == 0 && isContext(p.Type()) {
			continue
		}
		name := p.Name()
		if name == "" || name == "_" {
			if impl == nil {
				impl = implParamNames(iface, method, sig)
			}
			name = ""
			if i < len(impl) && impl[i] != "_" {
				name = impl[i]
			}
		}
		names = append(names, fmt.Sprintf("%q", name))
	}
	return strings.Join(names, ", ")
}

func isContext(t types.Type) bool { return types.TypeString(t, nil) == "context.Context" }

// transmittable reports whether a value of t can be sent to another server.
func transmittable(t types.Type) bool {
	switch u := t.Underlying().(type) {
	case *types.Signature, *types.Chan:
		return false
	case *types.Interface:
		return u.Empty()
	case *types.Pointer:
		return transmittable(u.Elem())
	case *types.Slice:
		return transmittable(u.Elem())
	case *types.Map:
		return transmittable(u.Key()) && transmittable(u.Elem())
	}
	return true
}

func writeMethod(w *bytes.Buffer, storeField, typeName, local, name string, sig *types.Signature, qual types.Qualifier) {
	params := sig.Params()
	results := sig.Results()
	hasCtx := params.Len() > 0 && isContext(params.At(0).Type())
	var decl, call, args []string
	ok := hasCtx
	for i := 0; i < params.Len(); i++ {
		p := params.At(i)
		pname := fmt.Sprintf("a%d", i)
		if i == 0 && hasCtx {
			pname = "ctx"
		}
		t := types.TypeString(p.Type(), qual)
		if sig.Variadic() && i == params.Len()-1 {
			t = "..." + types.TypeString(p.Type().(*types.Slice).Elem(), qual)
			call = append(call, pname+"...")
		} else {
			call = append(call, pname)
		}
		decl = append(decl, pname+" "+t)
		if i > 0 || !hasCtx {
			if !transmittable(p.Type()) || strings.HasSuffix(types.TypeString(p.Type(), nil), "persistence.Tx") {
				ok = false
			}
			args = append(args, pname)
		}
	}
	var res, resNames, resPtrs []string
	errLast := results.Len() > 0 && types.TypeString(results.At(results.Len()-1).Type(), nil) == "error"
	for i := 0; i < results.Len(); i++ {
		t := results.At(i).Type()
		if !transmittable(t) && !(i == results.Len()-1 && errLast) {
			ok = false
		}
		res = append(res, fmt.Sprintf("r%d %s", i, types.TypeString(t, qual)))
		resNames = append(resNames, fmt.Sprintf("r%d", i))
		resPtrs = append(resPtrs, fmt.Sprintf("&r%d", i))
	}
	fmt.Fprintf(w, "func (s *%s) %s(%s) (%s) {\n", typeName, name, strings.Join(decl, ", "), strings.Join(res, ", "))
	localCall := fmt.Sprintf("%s.%s(%s)", local, name, strings.Join(call, ", "))
	ret := "return " + localCall
	if results.Len() == 0 {
		ret = localCall + "\n\treturn"
	}
	switch {
	case ok && errLast:
		fmt.Fprintf(w, "\tif s.r.Remote(ctx, %q, %q, []any{%s}, func() []any { %s = %s; return []any{%s} }, %s) {\n\t\treturn\n\t}\n",
			storeField, name, strings.Join(args, ", "), strings.Join(resNames, ", "), localCall, strings.Join(resNames, ", "), strings.Join(resPtrs, ", "))
	case errLast && hasCtx:
		fmt.Fprintf(w, "\tif s.r.Refuse(ctx, %q, []any{%s}) {\n\t\tr%d = ErrUnsupported\n\t\treturn\n\t}\n", storeField, stringArgs(params, hasCtx), results.Len()-1)
	}
	fmt.Fprintf(w, "\t%s\n}\n\n", ret)
}

func stringArgs(params *types.Tuple, hasCtx bool) string {
	var out []string
	for i := 0; i < params.Len(); i++ {
		if i == 0 && hasCtx {
			continue
		}
		if transmittable(params.At(i).Type()) {
			out = append(out, fmt.Sprintf("a%d", i))
		}
	}
	return strings.Join(out, ", ")
}
