func TestAutomationDispatchIdentityAdmissionRollback(t *testing.T) {
	db := testutil.NewTestDB(t)
	ctx := t.Context()
	fixture := seedAutomationLiveCountsDefinition(t, db, map[string]string{"trigger": "trigger"})
	repo := NewAutomationRepo(db)
	tasks := NewTaskRepo(db, nil)
	task := createRuntimeScheduledTask(t, ctx, tasks, fixture.ProjectID, "Identity dispatch")
	schedule := createRuntimeAutomationSchedule(t, ctx, db, fixture, task.ID, fixture.Nodes["trigger"], time.Now().UTC().Add(-time.Minute).Truncate(time.Second))
	_, dispatch, err := repo.ClaimScheduledOccurrence(ctx, schedule, time.Now().UTC(), nil)
	require.NoError(t, err)
	require.NotNil(t, dispatch)
	leased, err := repo.LeaseNextDispatch(ctx, "lease", time.Now().UTC(), time.Minute)
	require.NoError(t, err)
	require.NotNil(t, leased)
	_, err = db.Exec(`INSERT INTO users(id,username) VALUES('dispatch-user','dispatch-user'); INSERT INTO org_memberships VALUES('default','dispatch-user','member')`)
	require.NoError(t, err)
	actor := models.WithPrincipal(ctx, models.Principal{UserID: "dispatch-user", Role: "owner"})
	_, err = tasks.ClaimAutomationDispatch(actor, leased.ID, "lease")
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	access := NewProjectAccessRepo(db)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "dispatch-user", "maintainer"))
	_, err = db.Exec(`CREATE TRIGGER reject_dispatch_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='execution.run_as' BEGIN SELECT RAISE(ABORT,'audit unavailable'); END`)
	require.NoError(t, err)
	_, err = tasks.ClaimAutomationDispatch(actor, leased.ID, "lease")
	require.ErrorContains(t, err, "audit unavailable")
	var count int
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM executions WHERE dispatch_id=?`, leased.ID).Scan(&count))
	require.Zero(t, count)
	stored, err := tasks.GetByID(ctx, task.ID)
	require.NoError(t, err)
	require.Equal(t, models.StatusPending, stored.Status)
	_, err = db.Exec(`DROP TRIGGER reject_dispatch_audit`)
	require.NoError(t, err)
	execution, err := tasks.ClaimAutomationDispatch(actor, leased.ID, "lease")
	require.NoError(t, err)
	saved, found, err := NewRunIdentityRepo(db).ExecutionUser(ctx, execution.ID)
	require.NoError(t, err)
	require.True(t, found)
	require.Equal(t, "dispatch-user", saved)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "dispatch-user", ""))
	_, err = tasks.ClaimAutomationDispatch(ctx, leased.ID, "lease")
	require.ErrorIs(t, err, persistence.ErrProjectDenied, "recovery rechecks the saved user even without caller identity")
}

func TestAutomationOccurrenceRechecksSavedScheduleUser(t *testing.T) {
	db := testutil.NewTestDB(t)
	ctx := t.Context()
	fixture := seedAutomationLiveCountsDefinition(t, db, map[string]string{"trigger": "trigger"})
	repo := NewAutomationRepo(db)
	task := createRuntimeScheduledTask(t, ctx, NewTaskRepo(db, nil), fixture.ProjectID, "Schedule identity")
	due := time.Now().UTC().Add(-time.Minute).Truncate(time.Second)
	schedule := createRuntimeAutomationSchedule(t, ctx, db, fixture, task.ID, fixture.Nodes["trigger"], due)
	_, err := db.Exec(`INSERT INTO users(id,username) VALUES('scheduler-user','scheduler-user'); INSERT INTO org_memberships VALUES('default','scheduler-user','member'); INSERT INTO schedule_run_identities(schedule_id,user_id) VALUES(?,'scheduler-user') ON CONFLICT(schedule_id) DO UPDATE SET user_id=excluded.user_id`, schedule.ID)
	require.NoError(t, err)
	actor := models.WithPrincipal(ctx, models.Principal{UserID: "scheduler-user", Role: "owner"})
	next := time.Now().UTC().Add(time.Hour)
	_, _, err = repo.ClaimScheduledOccurrence(actor, schedule, time.Now().UTC(), &next)
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	var count int
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM automation_invocations WHERE automation_id=?`, fixture.AutomationID).Scan(&count))
	require.Zero(t, count)
	var savedDue time.Time
	require.NoError(t, db.QueryRow(`SELECT next_run FROM schedules WHERE id=?`, schedule.ID).Scan(&savedDue))
	require.True(t, due.Equal(savedDue))
	access := NewProjectAccessRepo(db)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "scheduler-user", "maintainer"))
	owner := models.WithPrincipal(ctx, models.Principal{UserID: models.BootstrapUserID})
	_, _, err = repo.ClaimScheduledOccurrence(owner, schedule, time.Now().UTC(), &next)
	require.ErrorIs(t, err, persistence.ErrProjectDenied, "owner cannot replace the scheduler identity")
	invocation, _, err := repo.ClaimScheduledOccurrence(actor, schedule, time.Now().UTC(), &next)
	require.NoError(t, err)
	require.NotNil(t, invocation)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "scheduler-user", ""))
	_, _, err = repo.ClaimScheduledOccurrence(ctx, schedule, time.Now().UTC(), &next)
	require.ErrorIs(t, err, persistence.ErrProjectDenied, "existing occurrence recovery still checks saved permissions")
}

func TestManualAutomationAdmissionPermissionAndAuditRollback(t *testing.T) {
	db := testutil.NewTestDB(t)
	ctx := t.Context()
	fixture := seedAutomationLiveCountsDefinition(t, db, map[string]string{"trigger": "trigger"})
	repo := NewAutomationRepo(db)
	task := createRuntimeScheduledTask(t, ctx, NewTaskRepo(db, nil), fixture.ProjectID, "Manual identity")
	createRuntimeAutomationSchedule(t, ctx, db, fixture, task.ID, fixture.Nodes["trigger"], time.Now().UTC().Add(time.Hour))
	_, err := db.Exec(`INSERT INTO users(id,username) VALUES('manual-user','manual-user'); INSERT INTO org_memberships VALUES('default','manual-user','member')`)
	require.NoError(t, err)
	actor := models.WithPrincipal(ctx, models.Principal{UserID: "manual-user", Role: "owner"})
	_, _, err = repo.ClaimManualAutomationRun(actor, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	access := NewProjectAccessRepo(db)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "manual-user", "maintainer"))
	_, err = db.Exec(`CREATE TRIGGER fail_manual_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='automation.invocation.manual' BEGIN SELECT RAISE(ABORT,'audit unavailable'); END`)
	require.NoError(t, err)
	_, _, err = repo.ClaimManualAutomationRun(actor, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.ErrorContains(t, err, "audit unavailable")
	var count int
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM automation_invocations WHERE automation_id=?`, fixture.AutomationID).Scan(&count))
	require.Zero(t, count)
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM automation_task_run_reservations WHERE task_id=?`, task.ID).Scan(&count))
	require.Zero(t, count)
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM automation_invocation_users`).Scan(&count))
	require.Zero(t, count, "identity writes roll back with admission")
	_, err = db.Exec(`DROP TRIGGER fail_manual_audit`)
	require.NoError(t, err)
	invocations, dispatches, err := repo.ClaimManualAutomationRun(actor, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.NoError(t, err)
	require.Len(t, invocations, 1)
	require.Len(t, dispatches, 1)
	var actorID string
	require.NoError(t, db.QueryRow(`SELECT actor_user_id FROM project_audit_events WHERE action='automation.invocation.manual' AND target_id=?`, invocations[0].ID).Scan(&actorID))
	require.Equal(t, "manual-user", actorID)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "manual-user", ""))
	_, _, err = repo.ClaimManualAutomationRun(actor, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM automation_invocations WHERE automation_id=?`, fixture.AutomationID).Scan(&count))
	require.Equal(t, 1, count)
}

func TestAutomationPublisherRevocationBlocksAdmissionAndDispatch(t *testing.T) {
	db := testutil.NewTestDB(t)
	ctx := t.Context()
	fixture := seedAutomationLiveCountsDefinition(t, db, map[string]string{"trigger": "trigger"})
	repo := NewAutomationRepo(db)
	tasks := NewTaskRepo(db, nil)
	task := createRuntimeScheduledTask(t, ctx, tasks, fixture.ProjectID, "Publisher policy")
	schedule := createRuntimeAutomationSchedule(t, ctx, db, fixture, task.ID, fixture.Nodes["trigger"], time.Now().UTC().Add(-time.Minute).Truncate(time.Second))
	_, err := db.Exec(`INSERT INTO users(id,username) VALUES('version-publisher','version-publisher'); INSERT INTO org_memberships VALUES('default','version-publisher','member'); INSERT INTO automation_version_publishers(version_id,user_id) VALUES(?,'version-publisher')`, fixture.VersionID)
	require.NoError(t, err)
	// Neither a different owner nor legacy background context lends permissions.
	owner := models.WithPrincipal(ctx, models.Principal{UserID: models.BootstrapUserID})
	_, _, err = repo.ClaimManualAutomationRun(owner, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	_, _, err = repo.ClaimScheduledOccurrence(ctx, schedule, time.Now().UTC(), nil)
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	access := NewProjectAccessRepo(db)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "version-publisher", "maintainer"))
	_, dispatch, err := repo.ClaimScheduledOccurrence(ctx, schedule, time.Now().UTC(), nil)
	require.NoError(t, err)
	require.NotNil(t, dispatch)
	leased, err := repo.LeaseNextDispatch(ctx, "publisher-test", time.Now().UTC(), time.Minute)
	require.NoError(t, err)
	require.NotNil(t, leased)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "version-publisher", ""))
	_, err = tasks.ClaimAutomationDispatch(owner, leased.ID, "publisher-test")
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	_, _, err = repo.ClaimScheduledOccurrence(ctx, schedule, time.Now().UTC(), nil)
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	var count int
	require.NoError(t, db.QueryRow(`SELECT COUNT(*) FROM executions WHERE dispatch_id=?`, leased.ID).Scan(&count))
	require.Zero(t, count)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "version-publisher", "maintainer"))
	execution, err := tasks.ClaimAutomationDispatch(owner, leased.ID, "publisher-test")
	require.NoError(t, err)
	identities := NewRunIdentityRepo(db)
	require.NoError(t, identities.CheckExecutionGoal(ctx, execution.ID, task.ID))
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "version-publisher", ""))
	require.ErrorIs(t, identities.CheckExecutionGoal(ctx, execution.ID, task.ID), persistence.ErrProjectDenied, "running/recovered execution checks must also reject revoked publisher")
	_, err = db.Exec(`UPDATE executions SET status='queued' WHERE id=?`, execution.ID)
	require.NoError(t, err)
	require.ErrorIs(t, NewExecutionRepo(db).MarkRunning(owner, execution.ID), persistence.ErrProjectDenied)
	stored, err := NewExecutionRepo(db).GetByID(ctx, execution.ID)
	require.NoError(t, err)
	require.Equal(t, models.ExecQueued, stored.Status)
}

func TestInvocationIdentitySurvivesTaskReassignment(t *testing.T) {
	db := testutil.NewTestDB(t)
	ctx := t.Context()
	fixture := seedAutomationLiveCountsDefinition(t, db, map[string]string{"trigger": "trigger"})
	repo := NewAutomationRepo(db)
	tasks := NewTaskRepo(db, nil)
	task := createRuntimeScheduledTask(t, ctx, tasks, fixture.ProjectID, "Shared task")
	createRuntimeAutomationSchedule(t, ctx, db, fixture, task.ID, fixture.Nodes["trigger"], time.Now().UTC().Add(time.Hour))
	_, err := db.Exec(`INSERT INTO users(id,username) VALUES('initiator','initiator'); INSERT INTO org_memberships VALUES('default','initiator','member')`)
	require.NoError(t, err)
	access := NewProjectAccessRepo(db)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "initiator", "maintainer"))
	actor := models.WithPrincipal(ctx, models.Principal{UserID: "initiator"})
	invocations, dispatches, err := repo.ClaimManualAutomationRun(actor, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.NoError(t, err)
	require.Len(t, invocations, 1)
	require.Len(t, dispatches, 1)
	var userID string
	require.NoError(t, db.QueryRow(`SELECT user_id FROM automation_invocation_users WHERE invocation_id=?`, invocations[0].ID).Scan(&userID))
	require.Equal(t, "initiator", userID)
	owner := models.WithPrincipal(ctx, models.Principal{UserID: models.BootstrapUserID})
	require.NoError(t, NewRunIdentityRepo(db).BindTask(owner, task.ID))
	leased, err := repo.LeaseNextDispatch(ctx, "identity-test", time.Now().UTC(), time.Minute)
	require.NoError(t, err)
	require.NotNil(t, leased)
	// Reassignment cannot lend the owner's rights to the revoked initiator.
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "initiator", ""))
	_, err = tasks.ClaimAutomationDispatch(owner, leased.ID, "identity-test")
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "initiator", "maintainer"))
	execution, err := tasks.ClaimAutomationDispatch(owner, leased.ID, "identity-test")
	require.NoError(t, err)
	userID, found, err := NewRunIdentityRepo(db).ExecutionUser(ctx, execution.ID)
	require.NoError(t, err)
	require.True(t, found)
	require.Equal(t, "initiator", userID)
	// Shared tasks have no compiler origin: invocation policy must still require
	// maintainer access, and cannot accept an altered execution identity.
	identities := NewRunIdentityRepo(db)
	require.NoError(t, identities.CheckExecutionGoal(ctx, execution.ID, task.ID))
	_, err = db.Exec(`UPDATE execution_run_identities SET user_id=? WHERE execution_id=?`, models.BootstrapUserID, execution.ID)
	require.NoError(t, err)
	require.ErrorIs(t, identities.CheckExecutionGoal(ctx, execution.ID, task.ID), persistence.ErrProjectDenied)
	_, err = db.Exec(`UPDATE execution_run_identities SET user_id='initiator' WHERE execution_id=?`, execution.ID)
	require.NoError(t, err)
	require.NoError(t, access.SetMember(ctx, models.BootstrapUserID, fixture.ProjectID, "initiator", ""))
	require.ErrorIs(t, identities.CheckExecutionGoal(ctx, execution.ID, task.ID), persistence.ErrProjectDenied)
	require.ErrorIs(t, NewExecutionRepo(db).MarkRunning(ctx, execution.ID), persistence.ErrProjectDenied)
	_, err = tasks.ClaimAutomationDispatch(ctx, leased.ID, "identity-test")
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
}
