package sqlite

import (
	"testing"
	"time"

	"github.com/openvibely/openvibely/internal/models"
	"github.com/openvibely/openvibely/internal/persistence"
	"github.com/openvibely/openvibely/internal/testutil"
	"github.com/stretchr/testify/require"
)

func TestAutomationExternalReservationAuthorizationAndRollback(t *testing.T) {
	db := testutil.NewTestDB(t)
	ctx := t.Context()
	owner := models.WithPrincipal(ctx, models.Principal{UserID: models.BootstrapUserID})
	fixture := seedAutomationLiveCountsDefinition(t, db, map[string]string{"trigger": "trigger"})
	task := createRuntimeScheduledTask(t, ctx, NewTaskRepo(db, nil), fixture.ProjectID, "External reservation")
	createRuntimeAutomationSchedule(t, ctx, db, fixture, task.ID, fixture.Nodes["trigger"], time.Now().UTC().Add(time.Hour))
	auth := NewSlackAuthRepo(db)
	entry := &models.SlackAuthorizedUser{ProjectID: fixture.ProjectID, SlackUserID: "sender"}
	require.NoError(t, auth.Create(owner, entry))
	require.NoError(t, auth.BindApplicationUser(owner, fixture.ProjectID, entry.ID, "workspace", models.BootstrapUserID))
	actor := models.WithSlackIngressIdentity(owner, models.SlackIngressIdentity{ProjectID: fixture.ProjectID, TeamID: "workspace", ExternalUserID: entry.SlackUserID, UserID: models.BootstrapUserID})
	repo := NewAutomationRepo(db)
	invocation, _, err := repo.ClaimManualAutomationRun(actor, fixture.ProjectID, fixture.AutomationID, time.Now().UTC())
	require.NoError(t, err)
	require.Len(t, invocation, 1)
	binding := models.AutomationBinding{AutomationID: fixture.AutomationID, VersionID: fixture.VersionID, NodeID: fixture.Nodes["trigger"], InvocationID: invocation[0].ID}
	reserve := func(caller models.Principal, key string) (string, error) {
		return repo.ReserveExternalActivity(models.WithPrincipal(ctx, caller), fixture.ProjectID, binding, key, "create_github_issue", "github_issue")
	}
	_, err = repo.ReserveExternalActivity(owner, "default", binding, "foreign-project", "create_github_issue", "github_issue")
	require.ErrorIs(t, err, persistence.ErrProjectDenied, "invocation cannot authorize another project")
	_, err = db.Exec(`INSERT INTO users(id,username) VALUES('external-editor','external-editor'); INSERT INTO org_memberships VALUES('default','external-editor','member')`)
	require.NoError(t, err)
	_, err = reserve(models.Principal{UserID: "external-editor", Role: "owner"}, "denied")
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	_, err = db.Exec(`CREATE TRIGGER reject_external_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='automation.external_reserved' BEGIN SELECT RAISE(ABORT,'audit unavailable'); END`)
	require.NoError(t, err)
	_, err = reserve(models.Principal{UserID: models.BootstrapUserID}, "external")
	require.ErrorContains(t, err, "audit unavailable")
	var count int
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM automation_activities WHERE activity_key='external'`).Scan(&count))
	require.Zero(t, count)
	_, err = db.Exec(`DROP TRIGGER reject_external_audit`)
	require.NoError(t, err)
	_, err = reserve(models.Principal{UserID: models.BootstrapUserID}, "external")
	require.NoError(t, err)
	_, err = reserve(models.Principal{UserID: models.BootstrapUserID}, "cleanup")
	require.NoError(t, err)
	editor := models.WithPrincipal(ctx, models.Principal{UserID: "external-editor", Role: "owner"})
	require.ErrorIs(t, repo.ReleaseExternalActivityReservation(editor, fixture.ProjectID, binding, "cleanup"), persistence.ErrProjectDenied)
	require.ErrorIs(t, repo.ReleaseExternalActivityReservation(owner, "default", binding, "cleanup"), persistence.ErrProjectDenied)
	_, err = db.Exec(`CREATE TRIGGER reject_release_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='automation.external_released' BEGIN SELECT RAISE(ABORT,'release audit unavailable'); END`)
	require.NoError(t, err)
	require.ErrorContains(t, repo.ReleaseExternalActivityReservation(owner, fixture.ProjectID, binding, "cleanup"), "release audit unavailable")
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM automation_activities WHERE activity_key='cleanup'`).Scan(&count))
	require.Equal(t, 1, count)
	_, err = db.Exec(`DROP TRIGGER reject_release_audit`)
	require.NoError(t, err)
	require.NoError(t, repo.ReleaseExternalActivityReservation(owner, fixture.ProjectID, binding, "cleanup"))
	require.NoError(t, repo.ReleaseExternalActivityReservation(owner, fixture.ProjectID, binding, "cleanup"))
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM project_audit_events WHERE action='automation.external_released'`).Scan(&count))
	require.Equal(t, 1, count, "no-op releases must not create mutation audits")
	_, err = reserve(models.Principal{UserID: models.BootstrapUserID}, "revoked-cleanup")
	require.NoError(t, err)
	_, err = db.Exec(`INSERT INTO automation_activity_resources(activity_id,resource_type,resource_id,relation) SELECT id,'github_issue','42','output' FROM automation_activities WHERE activity_key='external'`)
	require.NoError(t, err)
	resource, err := reserve(models.Principal{UserID: models.BootstrapUserID}, "external")
	require.NoError(t, err)
	require.Equal(t, "42", resource)
	require.NoError(t, repo.ReleaseExternalActivityReservation(owner, fixture.ProjectID, binding, "external"))
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM automation_activities WHERE activity_key='external'`).Scan(&count))
	require.Equal(t, 1, count, "resource-bearing reservation cannot be released")
	source := persistence.AutomationGitHubIssueDedupSource{Context: models.AutomationContext{ProjectID: fixture.ProjectID, Bindings: []models.AutomationBinding{binding}}, TaskID: task.ID, ExecutionID: "test-execution"}
	_, err = repo.AcquireGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "release", "release-owner", source, time.Now(), time.Minute)
	require.NoError(t, err)
	require.ErrorIs(t, repo.ReleaseGitHubIssueDedupLease(editor, fixture.ProjectID, "owner/repo", "release", "release-owner"), persistence.ErrProjectDenied)
	require.Error(t, repo.ReleaseGitHubIssueDedupLease(owner, "default", "owner/repo", "release", "release-owner"))
	require.Error(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "release", "wrong-owner"))
	_, err = db.Exec(`CREATE TRIGGER reject_dedup_release_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='automation.github_issue_released' BEGIN SELECT RAISE(ABORT,'release audit unavailable'); END`)
	require.NoError(t, err)
	require.ErrorContains(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "release", "release-owner"), "release audit unavailable")
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM automation_github_issue_dedup_leases WHERE title_fingerprint='release'`).Scan(&count))
	require.Equal(t, 1, count)
	_, err = db.Exec(`DROP TRIGGER reject_dedup_release_audit`)
	require.NoError(t, err)
	require.NoError(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "release", "release-owner"))
	require.Error(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "release", "release-owner"))
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM project_audit_events WHERE action='automation.github_issue_released'`).Scan(&count))
	require.Equal(t, 1, count)
	_, err = repo.AcquireGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner", source, time.Now(), time.Minute)
	require.NoError(t, err)
	_, err = db.Exec(`CREATE TRIGGER reject_dispatch_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='automation.github_issue_dispatched' BEGIN SELECT RAISE(ABORT,'dispatch audit unavailable'); END`)
	require.NoError(t, err)
	require.ErrorContains(t, repo.MarkGitHubIssueDedupDispatched(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner"), "dispatch audit unavailable")
	var state string
	require.NoError(t, db.QueryRow(`SELECT mutation_state FROM automation_github_issue_dedup_leases WHERE title_fingerprint='fingerprint'`).Scan(&state))
	require.Equal(t, "reserved", state)
	_, err = db.Exec(`DROP TRIGGER reject_dispatch_audit`)
	require.NoError(t, err)
	require.ErrorIs(t, repo.MarkGitHubIssueDedupDispatched(editor, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner"), persistence.ErrProjectDenied)
	require.NoError(t, repo.MarkGitHubIssueDedupDispatched(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner"))
	require.ErrorContains(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner"), "not releasable")
	_, err = db.Exec(`CREATE TRIGGER reject_completion_audit BEFORE INSERT ON project_audit_events WHEN NEW.action='automation.github_issue_completed' BEGIN SELECT RAISE(ABORT,'completion audit unavailable'); END`)
	require.NoError(t, err)
	require.ErrorContains(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner", 42), "completion audit unavailable")
	require.NoError(t, db.QueryRow(`SELECT mutation_state FROM automation_github_issue_dedup_leases WHERE title_fingerprint='fingerprint'`).Scan(&state))
	require.Equal(t, "dispatched", state)
	_, err = db.Exec(`DROP TRIGGER reject_completion_audit`)
	require.NoError(t, err)
	require.NoError(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner", 42))
	require.NoError(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner", 42))
	require.Error(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner", 43))
	require.Error(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "wrong-owner", 42))
	require.Error(t, repo.CompleteGitHubIssueDedupLease(owner, "default", "owner/repo", "fingerprint", "lease-owner", 42))
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM project_audit_events WHERE action='automation.github_issue_completed'`).Scan(&count))
	require.Equal(t, 1, count, "idempotent completion must not duplicate audits")
	var auditActor string
	require.NoError(t, db.QueryRow(`SELECT actor_user_id FROM project_audit_events WHERE action='automation.github_issue_completed'`).Scan(&auditActor))
	require.Equal(t, models.BootstrapUserID, auditActor)
	_, err = repo.AcquireGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "late-outcome", "late-owner", source, time.Now(), time.Minute)
	require.NoError(t, err)
	require.Error(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "late-outcome", "late-owner", 99), "reserved lease is not an admitted provider action")
	require.NoError(t, repo.MarkGitHubIssueDedupDispatched(owner, fixture.ProjectID, "owner/repo", "late-outcome", "late-owner"))

	require.ErrorContains(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "lease-owner"), "not releasable")
	_, err = repo.AcquireGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "pending", "pending-owner", source, time.Now(), time.Minute)
	require.NoError(t, err)
	require.NoError(t, auth.DeleteForProject(owner, fixture.ProjectID, entry.ID))
	require.NoError(t, repo.CompleteGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "late-outcome", "late-owner", 99), "revocation must not hide a provider effect already dispatched")

	require.ErrorIs(t, repo.ReleaseGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "pending", "pending-owner"), persistence.ErrProjectDenied)
	require.ErrorIs(t, repo.MarkGitHubIssueDedupDispatched(owner, fixture.ProjectID, "owner/repo", "pending", "pending-owner"), persistence.ErrProjectDenied)
	require.NoError(t, db.QueryRow(`SELECT mutation_state FROM automation_github_issue_dedup_leases WHERE title_fingerprint='pending'`).Scan(&state))
	require.Equal(t, "reserved", state)
	_, err = repo.AcquireGitHubIssueDedupLease(owner, fixture.ProjectID, "owner/repo", "fingerprint", "reuse-owner", source, time.Now(), time.Minute)
	require.ErrorIs(t, err, persistence.ErrProjectDenied)

	require.ErrorIs(t, repo.ReleaseExternalActivityReservation(owner, fixture.ProjectID, binding, "revoked-cleanup"), persistence.ErrProjectDenied)
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM automation_activities WHERE activity_key='revoked-cleanup'`).Scan(&count))
	require.Equal(t, 1, count)

	_, err = reserve(models.Principal{UserID: models.BootstrapUserID}, "external")
	require.ErrorIs(t, err, persistence.ErrProjectDenied, "completed resource reuse must recheck the saved sender")
	_, err = reserve(models.Principal{UserID: models.BootstrapUserID}, "after-revocation")
	require.ErrorIs(t, err, persistence.ErrProjectDenied)
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM automation_activities WHERE activity_key='after-revocation'`).Scan(&count))
	require.Zero(t, count)
}
